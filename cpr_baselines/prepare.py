"""Prepare pinned upstream code and real checkpoints; never substitute scores."""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

from cpr_person.cache import atomic_json, canonical_hash, read_json, resolve, sha256_file
from .common import load_config


class ExternalCheckpointUnavailable(RuntimeError):
    pass


def asset_spec(cfg):
    return {key: cfg[key] for key in ("source", "assets") if key in cfg}


def git_output(path, *args):
    return subprocess.check_output(["git", "-C", str(path), *args], text=True).strip()


def validate_source(source):
    path = resolve(source["local_checkout"])
    if git_output(path, "rev-parse", "HEAD") != source["commit"]:
        raise RuntimeError("Official source commit differs from config")
    if git_output(path, "diff", "--name-only", "HEAD"):
        raise RuntimeError("Official source has tracked modifications")
    # Generated bytecode is allowed; other untracked Python modules could shadow
    # a pinned module and are rejected.
    for filename in git_output(path, "ls-files", "--others", "--exclude-standard").splitlines():
        if filename.endswith(".py") and "__pycache__" not in Path(filename).parts:
            raise RuntimeError(f"Unexpected Python code in official source: {filename}")
    return path


def prepare_source(source):
    path = resolve(source["local_checkout"])
    if not (path / ".git").exists():
        if path.exists() and any(path.iterdir()):
            raise RuntimeError(f"Refusing to overwrite non-git source directory: {path}")
        path.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "--no-checkout", source["repository"], str(path)], check=True)
        subprocess.run(["git", "-C", str(path), "checkout", "--detach", source["commit"]], check=True)
    validate_source(source)
    return {"repository": source["repository"], "commit": source["commit"],
            "path": str(path), "tracked_sha256": source_hash(path)}


def source_hash(path):
    return canonical_hash([{ "path": filename, "sha256": sha256_file(path / filename)}
                           for filename in git_output(path, "ls-files").splitlines()])


def file_info(path):
    return {"path": str(path), "size": path.stat().st_size, "sha256": sha256_file(path)}


def prepare_hf(asset, force):
    from huggingface_hub import snapshot_download
    revision = str(asset["revision"])
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("HF revision must be a pinned 40-character commit")
    path = resolve(asset["path"])
    path.mkdir(parents=True, exist_ok=True)
    snapshot_download(repo_id=asset["repo_id"], revision=revision, local_dir=str(path),
                      allow_patterns=["*.json", "*.safetensors", "*.txt", "*.model", "*.py"],
                      force_download=force)
    files = [p for p in sorted(path.rglob("*")) if p.is_file()
             and ".cache" not in p.relative_to(path).parts]
    if not (path / "config.json").is_file() or not any(p.suffix == ".safetensors" for p in files):
        raise RuntimeError(f"Incomplete HF model snapshot: {path}")
    return {"kind": "hf", "path": str(path), "repo_id": asset["repo_id"], "revision": revision,
            "files": [{**file_info(p), "relative_path": str(p.relative_to(path))} for p in files]}


def prepare_checkpoint(asset, force):
    path = resolve(asset["path"])
    path.parent.mkdir(parents=True, exist_ok=True)
    expected = asset.get("sha256")
    if (path.is_file() and path.stat().st_size > 0 and not force
            and (expected is None or sha256_file(path) == expected)):
        return {"kind": asset["kind"], **file_info(path), "locator": locator(asset)}
    temp = path.with_name(path.name + ".download.partial")
    try:
        if asset["kind"] == "url":
            with urllib.request.urlopen(asset["url"], timeout=60) as source, temp.open("wb") as target:
                shutil.copyfileobj(source, target, length=1024 * 1024)
        elif asset["kind"] == "hf_file":
            from huggingface_hub import hf_hub_download
            remote = hf_hub_download(repo_id=asset["repo_id"], filename=asset["filename"],
                                     revision=asset["revision"], force_download=force)
            shutil.copyfile(remote, temp)
        elif asset["kind"] == "gdrive":
            import gdown
            if gdown.download(id=asset["file_id"], output=str(temp), quiet=False) is None:
                raise ExternalCheckpointUnavailable("Official Context-I2W Google Drive download unavailable")
        else:
            raise ValueError(f"Unknown asset kind: {asset['kind']}")
        if not temp.is_file() or not temp.stat().st_size:
            raise ExternalCheckpointUnavailable("Checkpoint download produced no file")
        if asset.get("size_bytes") and temp.stat().st_size != asset["size_bytes"]:
            raise ValueError("Checkpoint size differs from the official release")
        if expected and sha256_file(temp) != expected:
            raise ValueError("Checkpoint SHA-256 differs from the pinned release")
        os.replace(temp, path)
    except (urllib.error.URLError, OSError) as error:
        raise ExternalCheckpointUnavailable(f"Could not download {path.name}: {error}") from error
    finally:
        temp.unlink(missing_ok=True)
    return {"kind": asset["kind"], **file_info(path), "locator": locator(asset)}


def locator(asset):
    return {key: asset[key] for key in ("url", "repo_id", "revision", "filename", "file_id") if key in asset}


def validate_prepared(cfg):
    marker = read_json(resolve(cfg["prepared_marker"]))
    if not isinstance(marker, dict) or marker.get("spec_hash") != canonical_hash(asset_spec(cfg)):
        raise RuntimeError("Missing/different prepared assets; run download_checkpoint.py first")
    assets = marker.get("assets", {})
    if set(assets) != set(cfg["assets"]):
        raise RuntimeError("Prepared asset inventory differs from config")
    for name, entry in assets.items():
        if resolve(entry["path"]) != resolve(cfg["assets"][name]["path"]):
            raise RuntimeError("Prepared asset path mismatch")
        if entry["kind"] == "git":
            asset = cfg["assets"][name]
            source = {"repository": asset["repository"], "commit": asset["revision"],
                      "local_checkout": asset["path"]}
            path = validate_source(source)
            if source_hash(path) != entry["tracked_sha256"]:
                raise RuntimeError("Prepared code asset bytes changed")
            continue
        infos = entry["files"] if entry["kind"] == "hf" else [entry]
        if not infos:
            raise RuntimeError("Empty prepared model inventory")
        for info in infos:
            path = Path(info["path"])
            if (not path.is_file() or path.stat().st_size != info["size"]
                    or sha256_file(path) != info["sha256"]):
                raise RuntimeError(f"Prepared asset bytes changed: {path}")
    if cfg.get("source"):
        path = validate_source(cfg["source"])
        if marker.get("source", {}).get("tracked_sha256") != source_hash(path):
            raise RuntimeError("Official source bytes changed")
    return marker


def prepare(cfg, force=False):
    if cfg.get("person_protocol"):
        from .person_cache import require_shared_context
        # Consume the already computed canonical detector/selector cache. The
        # captioner needs newer Transformers than the fixed detector runtime.
        # Never recompute shared grounding under the captioner's dependency set.
        require_shared_context(cfg, "cpu")
    marker_path = resolve(cfg["prepared_marker"])
    if not force:
        try:
            marker = validate_prepared(cfg)
            print("[skip] verified model assets and pinned source", flush=True)
            return marker
        except (RuntimeError, OSError, KeyError, ValueError):
            pass
    source = prepare_source(cfg["source"]) if cfg.get("source") else None
    entries = {}
    for name, asset in cfg["assets"].items():
        print(f"[prepare] {name}: {asset['path']}", flush=True)
        if asset["kind"] == "git":
            entries[name] = {"kind": "git", **prepare_source({
                "repository": asset["repository"], "commit": asset["revision"], "local_checkout": asset["path"]})}
        else:
            entries[name] = prepare_hf(asset, force) if asset["kind"] == "hf" else prepare_checkpoint(asset, force)
    marker = {"spec_hash": canonical_hash(asset_spec(cfg)), "assets": entries, "source": source}
    atomic_json(marker_path, marker)
    return validate_prepared(cfg)


def main(config_path):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=str(config_path))
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    try:
        prepare(load_config(resolve(args.config)), args.force)
    except ExternalCheckpointUnavailable as error:
        print(str(error), file=sys.stderr)
        raise SystemExit(42) from error
